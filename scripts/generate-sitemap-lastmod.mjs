import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PUBLIC_ROUTE_ENTRIES } from '../src/lib/route-registry.js';

// Routes whose CONTENT is regenerated from daily puzzle data even though
// their source files rarely change. They get no entry here: the sitemap
// server falls back to the current puzzle date for them, which is the
// honest lastmod. Stamping their last source edit would freeze the date.
const DAILY_DRIVEN_ROUTES = new Set(['/', '/today', '/archive', '/wordle-hints']);

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const outputPath = path.join(projectRoot, 'src', 'lib', 'generated', 'sitemap-lastmod.ts');

const WORDLEBOT_VARIANT_SOLVER_ROUTES = new Set([
	'/canuckle-solver',
	'/quordle-solver',
	'/dordle-solver',
	'/octordle-solver',
	'/thirdle-solver',
	'/hardle-solver',
	'/warmle-solver',
	'/woodle-solver',
	'/w-peaks-solver',
	'/xordle-solver',
	'/fibble-solver',
	'/spotle-wordle-solver'
]);

function normalizeDate(date) {
	return date.toISOString().slice(0, 10);
}

function buildRouteCandidates(route) {
	const routePart = route === '/' ? '' : route.replace(/^\/+/, '');
	const candidates = [];
	const baseRouteDirs = ['', '(content)', '(interactive)'];
	const sourceFiles = ['+page.svelte', '+page.server.ts', '+page.ts'];

	for (const baseDir of baseRouteDirs) {
		for (const sourceFile of sourceFiles) {
			const target = route === '/'
				? path.join(projectRoot, 'src', 'routes', sourceFile)
				: path.join(projectRoot, 'src', 'routes', baseDir, routePart, sourceFile);
			candidates.push(target);
		}
	}

	if (/^\/\d+-letter-wordle-solver$/.test(route)) {
		for (const sourceFile of sourceFiles) {
			candidates.push(
				path.join(
					projectRoot,
					'src',
					'routes',
					'(interactive)',
					'[wordLength=wordlebotLength]-letter-wordle-solver',
					sourceFile
				)
			);
		}
	}

	if (WORDLEBOT_VARIANT_SOLVER_ROUTES.has(route)) {
		for (const sourceFile of sourceFiles) {
			candidates.push(
				path.join(
					projectRoot,
					'src',
					'routes',
					'(interactive)',
					'[variant=wordlebotVariant]-solver',
					sourceFile
				)
			);
		}
	}

	// Guide articles all render from one dynamic route file plus the shared
	// content registry, so every /guides/<slug> resolves to the same mtimes.
	if (/^\/guides\/[^/]+$/.test(route)) {
		for (const sourceFile of sourceFiles) {
			candidates.push(
				path.join(projectRoot, 'src', 'routes', '(content)', 'guides', '[slug]', sourceFile)
			);
		}
		candidates.push(path.join(projectRoot, 'src', 'lib', 'content', 'guides.ts'));
	}

	return [...new Set(candidates)];
}

function getGitLastModified(files) {
	// The newest commit date touching any of the route's source files.
	// File mtimes are useless for this: CI checkouts stamp every file with
	// the build time, which made every sitemap URL claim it changed today.
	// The publish workflow checks out with fetch-depth: 0, so full history
	// is available here. Falls back to null when git has nothing to say.
	try {
		const out = execFileSync('git', ['log', '-1', '--format=%cs', '--', ...files], {
			cwd: projectRoot,
			encoding: 'utf8',
			stdio: ['ignore', 'pipe', 'ignore']
		}).trim();
		return /^\d{4}-\d{2}-\d{2}$/.test(out) ? out : null;
	} catch {
		return null;
	}
}

function getRouteLastModified(route) {
	const files = buildRouteCandidates(route).filter((candidate) => existsSync(candidate));

	if (files.length === 0) {
		return null;
	}

	const gitDate = getGitLastModified(files);
	if (gitDate) {
		return gitDate;
	}

	const mtimes = files.map((candidate) => statSync(candidate).mtime);
	const latest = mtimes.reduce((currentLatest, candidate) =>
		candidate.getTime() > currentLatest.getTime() ? candidate : currentLatest
	);

	return normalizeDate(latest);
}

function generateManifest() {
	const entries = Object.fromEntries(
		PUBLIC_ROUTE_ENTRIES.filter((route) => !DAILY_DRIVEN_ROUTES.has(route))
			.map((route) => [route, getRouteLastModified(route)])
			.filter(([, lastmod]) => Boolean(lastmod))
	);

	const output = `// Generated by scripts/generate-sitemap-lastmod.mjs. Do not edit manually.\n` +
		`export const GENERATED_SITEMAP_LASTMOD: Record<string, string> = ${JSON.stringify(entries, null, '\t')};\n`;

	mkdirSync(path.dirname(outputPath), { recursive: true });
	writeFileSync(outputPath, output, 'utf8');
	console.log(`[sitemap-lastmod] Wrote ${path.relative(projectRoot, outputPath)}`);
}

generateManifest();
